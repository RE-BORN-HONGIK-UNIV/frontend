const url = (id: string) => `/audio/lines/${id}.mp3`;

/** 문장에 맞는 mp3 주소들. 통째로 있으면 1개, "공감 한마디 + 다음 질문"처럼 두 문장을 붙인 거면 2개, 없으면 null */
export function prerecordedUrls(text: string): string[] | null {
  const t = text.trim();
  if (LINES[t]) return [url(LINES[t])];
  for (const [first, id] of Object.entries(LINES)) {
    const rest = t.startsWith(first + ' ') ? t.slice(first.length + 1) : null;
    if (rest && LINES[rest]) return [url(id), url(LINES[rest])];
  }
  return null;
}
